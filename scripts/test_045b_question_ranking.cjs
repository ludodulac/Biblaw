const fs=require('fs'),vm=require('vm'),assert=require('assert');
const js=fs.readFileSync('js/biblaw.js','utf8');
const start=js.indexOf('  function thematicQuestionTokens('),end=js.indexOf('  function intersectionItems(',start);
assert(start>0&&end>start);
const code=js.slice(start,end);
const dir=JSON.parse(fs.readFileSync('data/thematic-index/theme-directory-public.json','utf8'));
const catalog=JSON.parse(fs.readFileSync('data/browser-search-catalog.json','utf8'));
console.log('catalog shape',Object.keys(catalog));
const records=Array.isArray(catalog)?catalog:(catalog.records||catalog.items||[]);
const theme=dir.themes.find(x=>x.id==='mort');
assert(theme&&theme.occurrences.length>=161,'Mort thematic directory missing');
const state={recordById:new Map(records.map(r=>[r.id,r]))};
const context={state,selectedTypes:()=>new Set(['psalm']),$:()=>({value:''}),importanceRank:v=>({central:0,important:1,related:2})[v]??3,console};
vm.createContext(context);vm.runInContext(code+';this.thematicItems=thematicItems;',context);
const question="Que devient l'homme après la mort ?";
const baseline=Array.from(context.thematicItems([theme])).map(x=>x.record.id);
const ranked=Array.from(context.thematicItems([theme],question)).map(x=>x.record.id);
const direct=['book-03-psalm-005','book-19-psalm-121','book-22-psalm-155','book-22-psalm-159','book-21-psalm-161'];
const positions=arr=>direct.map(id=>arr.indexOf(id)+1);
const top=(arr,n)=>direct.filter(id=>arr.slice(0,n).includes(id)).length;
const result={baseline:positions(baseline),ranked:positions(ranked),a_top5_before:top(baseline,5),a_top5_after:top(ranked,5),a_top10_before:top(baseline,10),a_top10_after:top(ranked,10),baseline_length:baseline.length,ranked_length:ranked.length};
console.log(JSON.stringify(result,null,2));
assert.deepStrictEqual(positions(baseline),[1,5,13,14,15]);
assert.strictEqual(new Set(ranked).size,ranked.length);
assert.strictEqual(ranked.length,baseline.length);
assert(result.a_top5_after>result.a_top5_before||result.a_top10_after>result.a_top10_before,'no measurable improvement');
assert.deepStrictEqual(Array.from(context.thematicItems([theme])).map(x=>x.record.id),baseline,'general browsing order changed');
fs.writeFileSync('045b-ranking-result.json',JSON.stringify(result,null,2));
